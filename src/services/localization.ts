export function tr(text: string, language: AppLanguage): string {
  return language === 'no' ? no[text] ?? text : text;
}

/** Label for how long until a card comes back, e.g. "Tomorrow" or "In 3 weeks". */
export function formatReviewInterval(days: number, language: AppLanguage): string {
  const norwegian = language === 'no';
  if (days <= 1) return norwegian ? 'I morgen' : 'Tomorrow';
  if (days < 21) return norwegian ? `Om ${days} dager` : `In ${days} days`;
  if (days < 60) {
    const weeks = Math.round(days / 7);
    return norwegian ? `Om ${weeks} uker` : `In ${weeks} weeks`;
  }
  const months = Math.round(days / 30);
  return norwegian ? `Om ${months} md.` : `In ${months} months`;
}
